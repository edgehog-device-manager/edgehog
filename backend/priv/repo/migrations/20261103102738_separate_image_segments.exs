  defp parse_port(port), do: String.to_integer(port)

  defp build_reference(row) do
    registry = build_registry(row.registry_host, row.registry_port)

    prefix =
      [registry, row.repository]
      |> Enum.reject(&is_nil/1)
      |> Enum.join("/")

    name_with_prefix =
      if prefix == "" do
        row.image
      else
        "#{prefix}/#{row.image}"
      end

    name_with_prefix
    |> append_tag(row.tag)
    |> append_digest(row.digest)
  end

