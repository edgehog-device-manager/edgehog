defmodule Edgehog.Audit.Changes.RegisterEvent do
  @moduledoc """
  A change that registers an audit event about the create, update, destroy action
  being run on the resource, through `Edgehog.Audit.AuditService`.

  The event is registered after the action completed, for both success and failures,
  and the auditing never fails the action.

  For read or manual actions, see `Edgehog.Audit.Preparations.RegisterEvent` instead.

  Opts:
  - `:actor?`   :: boolean. Whether to include the actor (specified in the context, if
    any) in the registered event. Defaults to `true`.
  - `:metadata` :: map, optional. the metadata to be registered with the event
  """
  use Ash.Resource.Change

  alias Ash.Resource.Info
  alias Edgehog.Audit.AuditService

  require Logger

  @needed_keys [:actor?]

  @impl Ash.Resource.Change
  def init(opts) do
    opts = Keyword.put_new(opts, :metadata, %{})
    {_, errors} = Enum.reduce(@needed_keys, {opts, []}, &error_if_not_present/2)

    if Enum.empty?(errors) do
      {:ok, opts}
    else
      {:error, errors}
    end
  end

  @impl Ash.Resource.Change
  def change(changeset, opts, context) do
    attach_hooks(changeset, opts, context, changeset.params)
  end

  @impl Ash.Resource.Change
  def atomic(changeset, opts, context) do
    {:ok, attach_hooks(changeset, opts, context, changeset.params)}
  end

  defp attach_hooks(changeset, opts, context, original_params) do
    changeset
    |> Ash.Changeset.after_action(fn changeset, record ->
      register_success(changeset, record, opts, context, original_params)
    end)
    |> Ash.Changeset.after_transaction(fn
      changeset, {:error, error} ->
        register_failure(changeset, error, opts, context, original_params)
        {:error, error}

      _changeset, {:ok, result} ->
        {:ok, result}
    end)
  end

  defp register_success(subject, result, opts, context, original_params) do
    resource = subject.resource
    action = subject.action
    metadata = opts[:metadata]

    info = %{
      resource_module: resource,
      record_id: record_id(resource, result),
      action_name: action.name,
      action_type: action.type,
      action_inputs: action_inputs(subject, original_params),
      changed_attributes: changed_attributes(subject, original_params),
      actor: maybe_actor(opts, context)
    }

    message = "Running #{resource}.#{action.name}"

    case AuditService.info(
           message,
           ash_action_info: info,
           metadata: metadata,
           tenant: context.tenant
         ) do
      :ok ->
        {:ok, result}

      {:error, reason} ->
        # storing the event can fail (e.g. database errors): the audit event
        # must never fail the action being audited
        Logger.error("Failed to register the audit event: #{inspect(reason)}")
        {:ok, result}
    end
  end

  defp register_failure(subject, error, opts, context, original_params) do
    resource = subject.resource
    action = subject.action
    metadata = Map.put(opts[:metadata], :error, serialize_error(error))

    info = %{
      resource_module: resource,
      # a failed create never persisted a record: the primary key (generated by the
      # default or supplied by the client) points at nothing; update and destroy
      # failures still target an existing record
      record_id: if(action.type == :create, do: nil, else: record_id(resource, subject.data)),
      action_name: action.name,
      action_type: action.type,
      action_inputs: action_inputs(subject, original_params),
      changed_attributes: changed_attributes(subject, original_params),
      actor: maybe_actor(opts, context)
    }

    message = "Failed to run #{resource}.#{action.name}"

    case AuditService.error(
           message,
           ash_action_info: info,
           metadata: metadata,
           tenant: context.tenant
         ) do
      :ok ->
        :ok

      {:error, reason} ->
        # storing the event can fail (e.g. database errors): the audit event
        # must never fail the action being audited
        Logger.error("Failed to register the audit event: #{inspect(reason)}")
        :ok
    end
  end

  # Ash error structs
  defp serialize_error(error) when is_exception(error), do: Exception.message(error)

  defp serialize_error(errors) when is_list(errors),
    do: Enum.map_join(errors, "; ", &serialize_error/1)

  defp serialize_error(error), do: inspect(error)

  defp maybe_actor(opts, context) do
    if Keyword.fetch!(opts, :actor?), do: maybe_actor(context.actor), else: nil
  end

  defp maybe_actor(actor) when is_struct(actor), do: Map.from_struct(actor)
  defp maybe_actor(actor) when is_map(actor), do: actor
  defp maybe_actor(_actor), do: nil

  # the original input given to the action, filtered to resource attributes and
  # action arguments (input keys can be strings, e.g. JSON payloads)
  defp action_inputs(subject, original_params) do
    names = input_names(subject)

    original_params
    |> Enum.filter(fn {key, value} -> to_string(key) in names and json_encodable?(value) end)
    |> Map.new()
  end

  # values that cannot be Jason-encoded (e.g. Plug.Upload for file arguments)
  # make the audit event fail to store: skip them instead.
  defp json_encodable?(value) do
    match?({:ok, _}, Jason.encode(value))
  end

  defp input_names(subject) do
    attributes = subject.resource |> Info.attributes() |> Enum.map(& &1.name)
    arguments = Enum.map(subject.action.arguments, & &1.name)

    Enum.map(attributes ++ arguments, &to_string/1)
  end

  # attributes set during the action that were not part of the original input
  # (defaults, auto-generated values, business logic changes)
  defp changed_attributes(subject, original_params) do
    input_keys = MapSet.new(original_params, fn {key, _value} -> key end)
    source_attributes = subject.resource |> belongs_to_source_attributes() |> MapSet.new()

    Enum.reduce(subject.attributes, %{}, fn {attr_name, value}, acc ->
      if input_attribute?(attr_name, input_keys, source_attributes) do
        Map.put(acc, attr_name, value)
      else
        acc
      end
    end)
  end

  # belongs_to FK attributes are always captured, even when their name matches an
  # input key (e.g. an argument and the FK attribute sharing the same name)
  defp input_attribute?(attr_name, input_keys, source_attributes) do
    attr_name in source_attributes or
      (attr_name not in input_keys and to_string(attr_name) not in input_keys)
  end

  defp belongs_to_source_attributes(resource) do
    resource
    |> Info.relationships()
    |> Enum.filter(&(&1.type == :belongs_to))
    |> Enum.map(& &1.source_attribute)
  end

  defp record_id(resource, result) when is_map(result) do
    case Info.primary_key(resource) do
      [pk] ->
        union_id(Map.get(result, pk), attribute_union_type(resource, pk))

      # composite primary keys are not representable in ActionEventInfo.record_id,
      # which is a single value: fall back to no id instead of failing the audited action
      _composite_or_missing ->
        nil
    end
  end

  defp record_id(_resource, _record), do: nil

  defp union_id(value, type) when is_nil(value) or is_nil(type), do: nil
  defp union_id(value, type), do: %Ash.Union{type: type, value: value}

  defp attribute_union_type(resource, attribute_name),
    do: attribute_union_type(Info.attribute(resource, attribute_name))

  defp attribute_union_type(nil), do: nil
  defp attribute_union_type(attribute), do: base_type(attribute.type)

  # attribute types are normalized to modules (e.g. every primary key defined with
  # uuid_v7_primary_key in our code has type Ash.Type.UUIDv7, not the :uuid_v7 atom)
  defp base_type(Ash.Type.UUID), do: :uuid
  defp base_type(Ash.Type.UUIDv7), do: :uuid
  defp base_type(Ash.Type.Integer), do: :integer

  defp base_type(:uuid), do: :uuid
  defp base_type(:integer), do: :integer

  # NewType callbacks return the short name of the underlying base type (e.g.
  # Edgehog.Types.Id is a NewType of :integer), so recurse to resolve the wrapped
  # base type
  defp base_type(type) when is_atom(type) do
    if Code.ensure_loaded?(type) and function_exported?(type, :subtype_of, 0) do
      base_type(type.subtype_of())
    end
  end

  defp error_if_not_present(key, {opts, errors}) do
    error = "Missing key #{inspect(key)}."

    if Keyword.has_key?(opts, key) do
      {opts, errors}
    else
      {opts, [error | errors]}
    end
  end
end
